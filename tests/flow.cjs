const { chromium } = require('./pw.cjs');
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args:['--no-sandbox'] });
  const pg = await (await b.newContext({viewport:{width:400,height:860}})).newPage(); const errs=[];
  pg.on('pageerror', e=>errs.push(String(e.stack||e).split('\n').slice(0,4).join(' @ ')));
  await pg.goto((process.env.BASE_URL || 'http://127.0.0.1:8765') + '/quran-game.html', { waitUntil:'networkidle' });
  await pg.waitForTimeout(900);
  const r={};
  r.firstIsForm = await pg.locator('#npName').count()===1 && await pg.locator('#npOpen').count()===0;
  await pg.click('#mk'); r.emptyNameBlocked = await pg.locator('.startScreen').count()===1;
  await pg.click('#rcBtn'); r.restoreShown = !(await pg.locator('#rcForm').evaluate(e=>e.hidden));
  await pg.click('#rcBtn');
  await pg.click('#agRow [data-ag="small"]'); r.themeOnAge = await pg.evaluate(()=>document.documentElement.dataset.theme);
  await pg.fill('#npName','مُعاذ'); await pg.click('#chRow [data-c="hijab"]'); await pg.click('#mk');
  await pg.waitForTimeout(900);
  r.homeAfterCreate = await pg.locator('#goPlay').count()===1;
  r.startGone = await pg.locator('.startScreen').count()===0;
  r.homeHeroArtOk = await pg.locator('.heroArt').count()===1;
  r.savedChar = await pg.evaluate(()=>JSON.parse(localStorage.getItem('quran_game_v1_profiles'))[0].char);
  await pg.screenshot({path:'flow-home.png'});
  await pg.click('#cog'); await pg.waitForTimeout(500); await pg.click('#swUser'); await pg.waitForTimeout(700);
  r.listView = await pg.locator('#npOpen').count()===1 && await pg.locator('[data-p]').count()===1;
  r.fabHidden = await pg.evaluate(()=>document.getElementById('homeFab').hidden);
  await pg.click('#npOpen'); await pg.waitForTimeout(400);
  r.formHasBack = await pg.locator('#npBack').count()===1;
  await pg.click('#npBack'); await pg.waitForTimeout(400);
  r.backToList = await pg.locator('#npOpen').count()===1;
  await pg.click('[data-p]'); await pg.waitForTimeout(800);
  r.pickGoesHome = await pg.locator('#goPlay').count()===1;
  r.errs=errs; console.log(JSON.stringify(r));
  await b.close();
})();
